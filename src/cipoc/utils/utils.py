"""Configuration loading for CIPOC.

Loads a YAML config defining a default LLM configuration plus optional
per-agent overrides, expands ``${VAR}`` environment placeholders, and builds
merged :class:`~cipoc.llm.OpenAIConfig` / :class:`~cipoc.llm.RetryPolicy`
objects for each agent.
"""

from __future__ import annotations

import copy
import os
import re
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict, Field

from cipoc.llm import LLMConfig, RetryPolicy, config_for, llm_retry_policy


class DocumentsConfig(BaseModel):
    """Filesystem locations for source documents used by the pipeline.

    Paths are taken as-is from the config (CWD-relative unless absolute),
    consistent with how the config file itself is resolved. ``extra="allow"``
    leaves room for the planned document library to add fields without a
    loader change.
    """

    documents_path: Path = Field(
        default=Path("documents"),
        description="Directory holding the document library.",
    )
    data_dictionary_path: Path | None = Field(
        default=None,
        description="Path to the NAACCR data dictionary JSON.",
    )
    site_data_dictionary_path: Path | None = Field(
        default=None,
        description="Path to the CIPOC scoping dictionary JSON, generated by canonical-naaccr.",
    )
    variable_groups_path: Path = Field(
        default=Path("config/variable_groups.json"),
        description="Path to the JSON defining the extraction target variable groups (the orchestrator's plan).",
    )
    model_config = ConfigDict(extra="allow")

# User-edited runtime config; resolved relative to the current working directory.
DEFAULT_CONFIG_PATH = Path("config/config.yaml")

_ENV_PATTERN = re.compile(r"\$\{([^}]+)\}")

# Runtime-only constructor arguments for every agent's model wrapper. Only
# objects that cannot live in YAML belong here; settings that shape requests
# (model, endpoint, capacity) stay in raw config, where the run fingerprint
# records them.
RUNTIME_MODEL_KWARGS = frozenset({"http_client"})


def _expand_env(value: Any) -> Any:
    """Recursively expand ``${VAR}`` placeholders in strings using os.environ."""
    if isinstance(value, str):
        def replace(match: re.Match) -> str:
            var = match.group(1)
            if var not in os.environ:
                raise KeyError(f"Environment variable '{var}' referenced in config is not set")
            return os.environ[var]

        return _ENV_PATTERN.sub(replace, value)
    if isinstance(value, dict):
        return {k: _expand_env(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_expand_env(v) for v in value]
    return value


def _deep_merge(base: dict, override: dict) -> dict:
    """Return a deep merge of ``override`` onto ``base`` without mutating inputs."""
    merged = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _deep_merge(merged[key], value)
        else:
            merged[key] = copy.deepcopy(value)
    return merged


class CipocConfig:
    """Parsed CIPOC configuration with default LLM settings and agent overrides.

    ``model_kwargs`` carries runtime-only arguments (see
    :data:`RUNTIME_MODEL_KWARGS`) handed to every agent's model wrapper,
    including subagents built from an orchestrator's shared config. Values are
    shared by reference: never copied, serialized, fingerprinted, or closed here.
    """
    def __init__(self, raw: dict, *, model_kwargs: dict[str, Any] | None = None):
        unsupported = set(model_kwargs or {}) - RUNTIME_MODEL_KWARGS
        if unsupported:
            raise ValueError(
                f"Unsupported runtime model kwargs {sorted(unsupported)}; only "
                f"{sorted(RUNTIME_MODEL_KWARGS)} are allowed. Put request settings in the config file."
            )
        self._raw = raw
        self._model_kwargs: dict[str, Any] = dict(model_kwargs or {})
        self.defaults: dict = raw.get("llm", {}) or {}
        self.agents: dict[str, dict] = raw.get("agents", {}) or {}
        self._documents: dict = raw.get("documents", {}) or {}

    @property
    def model_kwargs(self) -> dict[str, Any]:
        """Runtime model-wrapper kwargs; a shallow copy, so values keep their identity."""
        return dict(self._model_kwargs)

    @classmethod
    def load(
        cls, path: str | Path | None = None, *, model_kwargs: dict[str, Any] | None = None
    ) -> "CipocConfig":
        """Load and parse a config file (defaults to ``config/config.yaml``)."""
        path = Path(path) if path is not None else DEFAULT_CONFIG_PATH
        if not path.exists():
            raise FileNotFoundError(
                f"Config file not found at '{path}'. Pass an explicit path to "
                f"load_config(), or create '{DEFAULT_CONFIG_PATH}' relative to the "
                f"working directory."
            )
        with open(path, "r") as f:
            raw = yaml.safe_load(f) or {}
        return cls(_expand_env(raw), model_kwargs=model_kwargs)

    def agent_settings(self, agent: str) -> dict:
        """Return the merged settings dict for ``agent`` (defaults + overrides)."""
        override = self.agents.get(agent) or {}
        return _deep_merge(self.defaults, override)

    def llm_config(self, agent: str | None = None) -> LLMConfig:
        """Build the provider-specific :class:`LLMConfig` for ``agent`` (or the
        defaults if None), choosing the config class from the ``provider`` setting."""
        settings = self.agent_settings(agent) if agent is not None else copy.deepcopy(self.defaults)
        # `retry` configures the graph, not the model client. OpenAIConfig allows
        # extra fields, so leaving it in would forward it to ChatOpenAI.
        settings.pop("retry", None)
        return config_for(settings.get("provider", "openai"))(**settings)

    def retry_policy(self, agent: str | None = None) -> RetryPolicy:
        """Build the LLM-node :class:`RetryPolicy` for ``agent`` (or the defaults
        if None). Config keys are ``RetryPolicy`` fields; anything omitted falls
        back to :data:`~cipoc.llm.DEFAULT_RETRY_SETTINGS`."""
        settings = self.agent_settings(agent) if agent is not None else copy.deepcopy(self.defaults)
        return llm_retry_policy(**(settings.get("retry") or {}))

    def documents(self) -> DocumentsConfig:
        """Build the :class:`DocumentsConfig` from the ``documents`` section."""
        return DocumentsConfig(**self._documents)


def load_config(
    path: str | Path | None = None, *, model_kwargs: dict[str, Any] | None = None
) -> CipocConfig:
    """Convenience wrapper around :meth:`CipocConfig.load`."""
    return CipocConfig.load(path, model_kwargs=model_kwargs)


__all__ = [
    "CipocConfig",
    "DocumentsConfig",
    "load_config",
    "DEFAULT_CONFIG_PATH",
    "RUNTIME_MODEL_KWARGS",
]
